import { useState, useRef } from 'react';
import { jsPDF } from 'jspdf';

// Helper to export CSV/Excel format
const downloadCsv = (_title: string, headers: string[], rows: any[][], filename: string) => {
  const csvContent =
    'data:text/csv;charset=utf-8,' +
    [headers.join(','), ...rows.map((r) => r.map((val) => `"${String(val).replace(/"/g, '""')}"`).join(','))].join('\n');
  const encodedUri = encodeURI(csvContent);
  const link = document.createElement('a');
  link.setAttribute('href', encodedUri);
  link.setAttribute('download', filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
};

// Helper to export beautifully formatted PDF Report
const downloadPdfReport = (
  reportTitle: string,
  headers: string[],
  rows: any[][],
  filename: string,
  summaryCards: { label: string; value: string }[],
) => {
  const doc = new jsPDF();

  // Primary Theme Color: Emerald Green (16, 185, 129)
  // Background/Slate Theme Color: (15, 23, 42)

  // Header Banner
  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, 210, 40, 'F');

  // Title
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(22);
  doc.setTextColor(16, 185, 129); // Emerald Green
  doc.text('OCCASIO ANALYTICS', 15, 18);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.setTextColor(148, 163, 184); // Slate 400
  doc.text('Platform Performance & Revenue Report', 15, 26);

  // Generate Date/Time
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139); // Slate 500
  doc.text(`Report Date: ${new Date().toLocaleString()}`, 130, 26);

  // Section: Overview
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(30, 41, 59); // Slate 800
  doc.text(reportTitle, 15, 52);

  // Draw Summary Cards
  let cardX = 15;
  const cardWidth = (210 - 30 - (summaryCards.length - 1) * 8) / summaryCards.length;
  
  summaryCards.forEach((card) => {
    // Card background
    doc.setFillColor(241, 245, 249); // slate 100
    doc.rect(cardX, 60, cardWidth, 22, 'F');
    
    // Left border (Emerald accent)
    doc.setFillColor(16, 185, 129);
    doc.rect(cardX, 60, 3, 22, 'F');

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139); // slate 500
    doc.text(card.label.toUpperCase(), cardX + 6, 68);

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.setTextColor(15, 23, 42); // slate 900
    doc.text(card.value, cardX + 6, 76);

    cardX += cardWidth + 8;
  });

  // Section: Data Table
  let currentY = 96;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(30, 41, 59);
  doc.text('Tabular Details', 15, currentY);
  currentY += 6;

  // Table Headers
  doc.setFillColor(15, 23, 42); // Dark slate header
  doc.rect(15, currentY, 180, 8, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);

  const colWidth = 180 / headers.length;
  headers.forEach((header, idx) => {
    doc.text(header, 17 + idx * colWidth, currentY + 5.5);
  });

  currentY += 8;

  // Table Rows
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(51, 65, 85); // slate 700

  rows.forEach((row, rowIdx) => {
    // Alternating Row Background
    if (rowIdx % 2 === 1) {
      doc.setFillColor(248, 250, 252); // slate 50
      doc.rect(15, currentY, 180, 8, 'F');
    }

    row.forEach((cell, cellIdx) => {
      doc.text(String(cell), 17 + cellIdx * colWidth, currentY + 5.5);
    });

    // Row separator
    doc.setDrawColor(241, 245, 249);
    doc.line(15, currentY + 8, 195, currentY + 8);

    currentY += 8;
  });

  // Footer Accent
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.text('Generated by Occasio Dashboard Core. All rights reserved.', 15, 285);

  doc.save(filename);
};

