interface AdminChartProps {
  trend: {
    year?: number;
    month?: number;
    label: string;
    subscription: number;
    publishing: number;
    commission: number;
    total: number;
    users: number;
    managers: number;
  }[];
}

export const AdminDashboardCharts = ({ trend }: AdminChartProps) => {
  const [activeSeries, setActiveSeries] = useState({
    subscription: true,
    publishing: true,
    commission: true,
    total: true,
  });

  const [hoveredIdx, setHoveredIdx] = useState<number | null>(null);
  const containerRef = useRef<HTMLDivElement>(null);

  if (!trend || trend.length === 0) return null;

  // Find max value for scaling financial chart
  const seriesKeys = Object.keys(activeSeries) as ('subscription' | 'publishing' | 'commission' | 'total')[];
  const maxVal = Math.max(
    ...trend.map((d) =>
      Math.max(...seriesKeys.map((k) => (activeSeries[k] ? d[k] : 0)))
    ),
    100
  );

  // Scaling helper values for SVG Line Chart
  const width = 600;
  const height = 280;
  const paddingLeft = 60;
  const paddingRight = 20;
  const paddingTop = 30;
  const paddingBottom = 40;
  const graphWidth = width - paddingLeft - paddingRight;
  const graphHeight = height - paddingTop - paddingBottom;

  const getCoordinates = (index: number, val: number) => {
    const x = paddingLeft + (index / (trend.length - 1)) * graphWidth;
    const y = paddingTop + graphHeight - (val / maxVal) * graphHeight;
    return { x, y };
  };

  // Generate SVG Path for a series
  const getPathData = (key: 'subscription' | 'publishing' | 'commission' | 'total') => {
    return trend
      .map((d, i) => {
        const { x, y } = getCoordinates(i, d[key]);
        return `${i === 0 ? 'M' : 'L'} ${x} ${y}`;
      })
      .join(' ');
  };

  // Generate SVG Area Path for total gradient
  const getAreaPathData = () => {
    const linePath = trend
      .map((d, i) => {
        const { x, y } = getCoordinates(i, d.total);
        return `L ${x} ${y}`;
      })
      .join(' ');

    const start = getCoordinates(0, 0);
    const end = getCoordinates(trend.length - 1, 0);
    return `M ${start.x} ${start.y} ${linePath} L ${end.x} ${end.y} Z`;
  };

  // Handle Export Functions
  const handleExportCsv = () => {
    const headers = ['Month', 'Subscription Rev (INR)', 'Publishing Rev (INR)', 'Commission Rev (INR)', 'Total Rev (INR)', 'User Registrations', 'Manager Registrations'];
    const rows = trend.map((d) => [
      d.label,
      d.subscription,
      d.publishing,
      d.commission,
      d.total,
      d.users,
      d.managers,
    ]);
    downloadCsv('Admin Dashboard Data', headers, rows, `admin-dashboard-stats-${new Date().toISOString().split('T')[0]}.csv`);
  };

  const handleExportPdf = () => {
    const headers = ['Month', 'Sub (₹)', 'Publish (₹)', 'Commission (₹)', 'Total (₹)', 'Users', 'Managers'];
    const rows = trend.map((d) => [
      d.label,
      `₹${d.subscription}`,
      `₹${d.publishing}`,
      `₹${d.commission}`,
      `₹${d.total}`,
      d.users,
      d.managers,
    ]);
    const totalRevAllTime = trend.reduce((sum, d) => sum + d.total, 0);
    const totalUsersAdded = trend.reduce((sum, d) => sum + d.users, 0);
    const totalManagersAdded = trend.reduce((sum, d) => sum + d.managers, 0);

    const summaryCards = [
      { label: 'Total Revenue (6m)', value: `₹${totalRevAllTime}` },
      { label: 'New Users (6m)', value: String(totalUsersAdded) },
      { label: 'New Managers (6m)', value: String(totalManagersAdded) },
    ];

    downloadPdfReport(
      'Admin Financial & Platform Overview',
      headers,
      rows,
      `admin-dashboard-report-${new Date().toISOString().split('T')[0]}.pdf`,
      summaryCards
    );
  };

  return (
    <div className="grid grid-cols-1 lg:grid-cols-3 gap-8 mb-10">
      {/* Financial Line Chart */}
      <div className="lg:col-span-2 bg-slate-900/40 backdrop-blur-xl border border-slate-800/60 rounded-3xl p-6 shadow-xl relative overflow-hidden flex flex-col">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 mb-6 relative z-10">
          <div>
            <h3 className="text-lg font-bold text-white flex items-center gap-2">
              <span>📈</span> Financial Performance
            </h3>
            <p className="text-xs text-slate-400 mt-1">Platform revenue breakdown over last 6 months</p>
          </div>
          <div className="flex gap-2">
            <button
              onClick={handleExportCsv}
              className="px-3 py-1.5 bg-emerald-500/10 hover:bg-emerald-500/20 text-emerald-400 text-xs font-semibold rounded-lg border border-emerald-500/20 transition-all flex items-center gap-1.5 cursor-pointer"
            >
              📥 CSV
            </button>
            <button
              onClick={handleExportPdf}
              className="px-3 py-1.5 bg-indigo-500/10 hover:bg-indigo-500/20 text-indigo-400 text-xs font-semibold rounded-lg border border-indigo-500/20 transition-all flex items-center gap-1.5 cursor-pointer"
            >
              📄 PDF
            </button>
          </div>
        </div>

        {/* Chart Series Toggle Legends */}
        <div className="flex flex-wrap gap-4 mb-6 text-xs font-medium z-10">
          <label className="flex items-center gap-2 text-indigo-400 cursor-pointer select-none">
            <input
              type="checkbox"
              checked={activeSeries.subscription}
              onChange={() => setActiveSeries({ ...activeSeries, subscription: !activeSeries.subscription })}
              className="accent-indigo-500 rounded"
            />
            Subscriptions
          </label>
          <label className="flex items-center gap-2 text-amber-400 cursor-pointer select-none">
            <input
              type="checkbox"
              checked={activeSeries.publishing}
              onChange={() => setActiveSeries({ ...activeSeries, publishing: !activeSeries.publishing })}
              className="accent-amber-500 rounded"
            />
            Publish Fee
          </label>
          <label className="flex items-center gap-2 text-sky-400 cursor-pointer select-none">
            <input
              type="checkbox"
              checked={activeSeries.commission}
              onChange={() => setActiveSeries({ ...activeSeries, commission: !activeSeries.commission })}
              className="accent-sky-500 rounded"
            />
            Commissions
          </label>
          <label className="flex items-center gap-2 text-emerald-400 cursor-pointer select-none">
            <input
              type="checkbox"
              checked={activeSeries.total}
              onChange={() => setActiveSeries({ ...activeSeries, total: !activeSeries.total })}
              className="accent-emerald-500 rounded"
            />
            Total Revenue
          </label>
        </div>

        {/* SVG Drawing Canvas */}
        <div className="relative flex-1 min-h-[280px]" ref={containerRef}>
          <svg viewBox={`0 0 ${width} ${height}`} className="w-full h-full text-slate-500">
            {/* Gradients */}
            <defs>
              <linearGradient id="total-grad" x1="0" y1="0" x2="0" y2="1">
                <stop offset="0%" stopColor="#10b981" stopOpacity="0.15" />
                <stop offset="100%" stopColor="#10b981" stopOpacity="0.0" />
              </linearGradient>
            </defs>

            {/* Background Grid Lines */}
            {[0, 0.25, 0.5, 0.75, 1].map((ratio, i) => {
              const y = paddingTop + ratio * graphHeight;
              const val = Math.round(maxVal * (1 - ratio));
              return (
                <g key={i}>
                  <line
                    x1={paddingLeft}
                    y1={y}
                    x2={width - paddingRight}
                    y2={y}
                    stroke="currentColor"
                    strokeOpacity={0.08}
                    strokeDasharray="4 4"
                  />
                  <text
                    x={paddingLeft - 8}
                    y={y + 4}
                    textAnchor="end"
                    className="text-[9px] fill-slate-500 font-semibold"
                  >
                    ₹{val}
                  </text>
                </g>
              );
            })}

            {/* X-Axis labels */}
            {trend.map((d, i) => {
              const x = paddingLeft + (i / (trend.length - 1)) * graphWidth;
              return (
                <text
                  key={i}
                  x={x}
                  y={height - paddingBottom + 18}
                  textAnchor="middle"
                  className="text-[10px] fill-slate-400 font-bold"
                >
                  {d.label}
                </text>
              );
            })}

            {/* Total Area Gradient */}
            {activeSeries.total && (
              <path d={getAreaPathData()} fill="url(#total-grad)" />
            )}

            {/* Lines for active series */}
            {activeSeries.subscription && (
              <path
                d={getPathData('subscription')}
                fill="none"
                stroke="#6366f1"
                strokeWidth={2.5}
                strokeLinecap="round"
                className="transition-all duration-300"
              />
            )}
            {activeSeries.publishing && (
              <path
                d={getPathData('publishing')}
                fill="none"
                stroke="#f59e0b"
                strokeWidth={2.5}
                strokeLinecap="round"
                className="transition-all duration-300"
              />
            )}
            {activeSeries.commission && (
              <path
                d={getPathData('commission')}
                fill="none"
                stroke="#0ea5e9"
                strokeWidth={2.5}
                strokeLinecap="round"
                className="transition-all duration-300"
              />
            )}
            {activeSeries.total && (
              <path
                d={getPathData('total')}
                fill="none"
                stroke="#10b981"
                strokeWidth={3}
                strokeLinecap="round"
                className="transition-all duration-300"
              />
            )}

            {/* Hover Guides & Dots */}
            {trend.map((_, i) => {
              const x = paddingLeft + (i / (trend.length - 1)) * graphWidth;
              return (
                <rect
                  key={i}
                  x={x - graphWidth / (trend.length * 2)}
                  y={paddingTop}
                  width={graphWidth / (trend.length - 1)}
                  height={graphHeight}
                  fill="transparent"
                  className="cursor-crosshair"
                  onMouseEnter={() => setHoveredIdx(i)}
                  onMouseLeave={() => setHoveredIdx(null)}
                />
              );
            })}

            {/* Render Vertical line & points on hover */}
            {hoveredIdx !== null && (
              <g>
                <line
                  x1={getCoordinates(hoveredIdx, 0).x}
                  y1={paddingTop}
                  x2={getCoordinates(hoveredIdx, 0).x}
                  y2={height - paddingBottom}
                  stroke="#334155"
                  strokeWidth={1.5}
                  strokeDasharray="2 2"
                />
                {seriesKeys.map((key) => {
                  if (!activeSeries[key]) return null;
                  const { x, y } = getCoordinates(hoveredIdx, trend[hoveredIdx][key]);
                  const colorMap = {
                    subscription: '#6366f1',
                    publishing: '#f59e0b',
                    commission: '#0ea5e9',
                    total: '#10b981',
                  };
                  return (
                    <circle
                      key={key}
                      cx={x}
                      cy={y}
                      r={5}
                      fill={colorMap[key]}
                      stroke="#0f172a"
                      strokeWidth={2}
                    />
                  );
                })}
              </g>
            )}
          </svg>

          {/* Interactive HTML Tooltip inside SVG wrapper */}
          {hoveredIdx !== null && (
            <div
              className="absolute bg-slate-955 border border-slate-800 rounded-xl p-3 shadow-2xl pointer-events-none text-xs flex flex-col gap-1 z-20 text-slate-300"
              style={{
                left: `${getCoordinates(hoveredIdx, 0).x + 10}px`,
                top: `${paddingTop + 10}px`,
              }}
            >
              <p className="font-bold text-white mb-1 border-b border-slate-800 pb-1">
                {trend[hoveredIdx].label} {trend[hoveredIdx].year}
              </p>
              {activeSeries.subscription && (
                <p className="flex justify-between gap-4">
                  <span>Subscription:</span>
                  <span className="text-indigo-400 font-bold">₹{trend[hoveredIdx].subscription}</span>
                </p>
              )}
              {activeSeries.publishing && (
                <p className="flex justify-between gap-4">
                  <span>Publishing:</span>
                  <span className="text-amber-400 font-bold">₹{trend[hoveredIdx].publishing}</span>
                </p>
              )}
              {activeSeries.commission && (
                <p className="flex justify-between gap-4">
                  <span>Commissions:</span>
                  <span className="text-sky-400 font-bold">₹{trend[hoveredIdx].commission}</span>
                </p>
              )}
              {activeSeries.total && (
                <p className="flex justify-between gap-4 border-t border-slate-800/80 pt-1 font-semibold text-white">
                  <span>Total Rev:</span>
                  <span className="text-emerald-400">₹{trend[hoveredIdx].total}</span>
                </p>
              )}
            </div>
          )}
        </div>
      </div>

      {/* User & Manager Signups Growth Bar Chart */}
      <div className="bg-slate-900/40 backdrop-blur-xl border border-slate-800/60 rounded-3xl p-6 shadow-xl flex flex-col">
        <h3 className="text-lg font-bold text-white mb-1 flex items-center gap-2">
          <span>👥</span> Account Growth
        </h3>
        <p className="text-xs text-slate-400 mb-6">User and Manager signups trend</p>

        <div className="flex-1 flex flex-col justify-between">
          <div className="flex flex-col gap-4">
            {trend.map((d, i) => {
              const maxUsers = Math.max(...trend.map((x) => x.users + x.managers), 1);
              const userPct = (d.users / maxUsers) * 100;
              const managerPct = (d.managers / maxUsers) * 100;

              return (
                <div key={i} className="flex items-center gap-3 text-xs">
                  <span className="w-8 text-slate-400 font-semibold">{d.label}</span>
                  <div className="flex-1 h-7 bg-slate-950/80 rounded-lg overflow-hidden flex border border-slate-800/50">
                    {d.users > 0 && (
                      <div
                        style={{ width: `${userPct}%` }}
                        className="bg-gradient-to-r from-emerald-600 to-emerald-400 h-full relative group flex items-center pl-2"
                        title={`${d.users} Users`}
                      >
                        <span className="text-[10px] text-emerald-950 font-extrabold">{d.users}</span>
                      </div>
                    )}
                    {d.managers > 0 && (
                      <div
                        style={{ width: `${managerPct}%` }}
                        className="bg-gradient-to-r from-indigo-600 to-indigo-400 h-full relative group flex items-center pl-2"
                        title={`${d.managers} Managers`}
                      >
                        <span className="text-[10px] text-indigo-950 font-extrabold">{d.managers}</span>
                      </div>
                    )}
                  </div>
                </div>
              );
            })}
          </div>

          <div className="flex justify-center gap-6 mt-6 text-xs font-semibold border-t border-slate-800/60 pt-4">
            <span className="flex items-center gap-2 text-emerald-400">
              <span className="w-3 h-3 rounded-full bg-emerald-400"></span> Users
            </span>
            <span className="flex items-center gap-2 text-indigo-400">
              <span className="w-3 h-3 rounded-full bg-indigo-400"></span> Managers
            </span>
          </div>
        </div>
      </div>
    </div>
  );
};

